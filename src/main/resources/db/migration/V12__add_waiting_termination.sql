ALTER TABLE waiting
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN end_reason VARCHAR(30),
    ADD COLUMN end_detail VARCHAR(300),
    ADD COLUMN ended_at TIMESTAMP WITH TIME ZONE;

-- 과거 EXPIRED에는 상세 사유와 종료 시각이 없으므로 임의로 추정하지 않는다.
UPDATE waiting SET status = 'NO_SHOW', end_reason = 'LEGACY_EXPIRED' WHERE status = 'EXPIRED';

CREATE TABLE waiting_end_history
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waiting_id      BIGINT NOT NULL REFERENCES waiting (id),
    previous_status VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    previous_reason VARCHAR(30),
    reason          VARCHAR(30) NOT NULL,
    previous_detail VARCHAR(300),
    detail          VARCHAR(300) NOT NULL,
    actor_id        BIGINT NOT NULL REFERENCES member (id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_waiting_end_history_waiting ON waiting_end_history (waiting_id, id);
