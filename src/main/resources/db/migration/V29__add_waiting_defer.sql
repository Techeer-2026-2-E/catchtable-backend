CREATE TABLE waiting_defer_history
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waiting_id      BIGINT NOT NULL REFERENCES waiting (id),
    before_position INTEGER NOT NULL,
    after_position  INTEGER NOT NULL,
    actor_id        BIGINT NOT NULL REFERENCES member (id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_waiting_defer_history_waiting ON waiting_defer_history (waiting_id, id);
